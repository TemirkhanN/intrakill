// Almost entirely generated by Claude. I didn't expect a mere clipboard copy-paste feature is so complicated in 2026
actual fun copyImageAttachmentToClipboard(attachment: Attachment) {
    val fs: Filesystem = Ioc.locate()
    val file = fs.getTmpFile("clipboard-image").withExtension(attachment.fileExtension())
    val bytes = attachment.content.use { it.readBytes() }
    file.outputStream().use { it.write(bytes) }

    val decoded = runCatching { ImageIO.read(ByteArrayInputStream(bytes)) }.getOrNull()

    val isMac = System.getProperty("os.name").lowercase().contains("mac")
    if (isMac) {
        val png =
            decoded?.let { img ->
                if (attachment.mimeType.equals("image/png", ignoreCase = true)) {
                    bytes
                } else {
                    ByteArrayOutputStream().also { ImageIO.write(img, "png", it) }.toByteArray()
                }
            }
        if (runCatching { MacPasteboard.copy(png, file) }.getOrDefault(false)) return
    }

    // Windows / Linux (and macOS fallback)
    Toolkit.getDefaultToolkit().systemClipboard.setContents(
        AwtImageTransferable(file, decoded?.toOpaqueRgb()),
        null,
    )
}

// ---------- macOS: NSPasteboard via the Objective-C runtime ----------
private interface ObjC : Library {
    @Suppress("ktlint:standard:function-naming")
    fun objc_getClass(name: String): Pointer

    @Suppress("ktlint:standard:function-naming")
    fun sel_registerName(name: String): Pointer

    // objc_msgSend is NOT variadic; declare exact signatures (matters on Apple Silicon)
    @Suppress("ktlint:standard:function-naming")
    fun objc_msgSend(
        receiver: Pointer,
        selector: Pointer,
    ): Pointer?

    @Suppress("ktlint:standard:function-naming")
    fun objc_msgSend(
        receiver: Pointer,
        selector: Pointer,
        a: String,
    ): Pointer?

    @Suppress("ktlint:standard:function-naming")
    fun objc_msgSend(
        receiver: Pointer,
        selector: Pointer,
        a: Pointer?,
    ): Pointer?

    @Suppress("ktlint:standard:function-naming")
    fun objc_msgSend(
        receiver: Pointer,
        selector: Pointer,
        a: Pointer?,
        b: Pointer?,
    ): Pointer?

    @Suppress("ktlint:standard:function-naming")
    fun objc_msgSend(
        receiver: Pointer,
        selector: Pointer,
        a: Pointer?,
        b: Long,
    ): Pointer?
}

private object MacPasteboard {
    private val objc: ObjC by lazy {
        NativeLibrary.getInstance("AppKit") // makes sure NSPasteboard is loaded
        Native.load("objc", ObjC::class.java)
    }

    private fun cls(name: String) = objc.objc_getClass(name)

    private fun sel(name: String) = objc.sel_registerName(name)

    private fun nsString(s: String) = objc.objc_msgSend(cls("NSString"), sel("stringWithUTF8String:"), s)

    /** Puts PNG image data (if available) and a file reference on the general pasteboard. */
    fun copy(
        png: ByteArray?,
        file: File,
    ): Boolean {
        val pasteboard = objc.objc_msgSend(cls("NSPasteboard"), sel("generalPasteboard")) ?: return false
        objc.objc_msgSend(pasteboard, sel("clearContents"))

        if (png != null && png.isNotEmpty()) {
            val mem = Memory(png.size.toLong()).apply { write(0, png, 0, png.size) }
            val data = objc.objc_msgSend(cls("NSData"), sel("dataWithBytes:length:"), mem, png.size.toLong())
            objc.objc_msgSend(pasteboard, sel("setData:forType:"), data, nsString("public.png"))
        }

        objc.objc_msgSend(
            pasteboard,
            sel("setString:forType:"),
            nsString(file.toPath().toUri().toString()), // file:///...
            nsString("public.file-url"),
        )
        return true
    }
}

// ---------- Windows / Linux: AWT ----------

private class AwtImageTransferable(
    private val file: File,
    private val image: Image?,
) : Transferable {
    private val flavors: Array<DataFlavor> =
        buildList {
            if (image != null) add(DataFlavor.imageFlavor)
            add(DataFlavor.javaFileListFlavor)
        }.toTypedArray()

    override fun getTransferDataFlavors() = flavors.copyOf()

    override fun isDataFlavorSupported(flavor: DataFlavor) = flavors.any { it.equals(flavor) }

    override fun getTransferData(flavor: DataFlavor): Any =
        when {
            image != null && flavor.equals(DataFlavor.imageFlavor) -> image
            flavor.equals(DataFlavor.javaFileListFlavor) -> listOf(file)
            else -> throw UnsupportedFlavorException(flavor)
        }
}

private fun BufferedImage.toOpaqueRgb(): BufferedImage {
    if (type == BufferedImage.TYPE_INT_RGB) return this
    val rgb = BufferedImage(width, height, BufferedImage.TYPE_INT_RGB)
    val g = rgb.createGraphics()
    try {
        g.color = Color.WHITE
        g.fillRect(0, 0, width, height)
        g.drawImage(this, 0, 0, null)
    } finally {
        g.dispose()
    }
    return rgb
}

private fun Attachment.fileExtension(): String =
    when (mimeType.lowercase()) {
        "image/jpeg" -> "jpg"
        "image/png" -> "png"
        "image/gif" -> "gif"
        "image/webp" -> "webp"
        else -> "img"
    }

private fun File.withExtension(extension: String): File {
    val target = File(parentFile, "$nameWithoutExtension.$extension")
    if (this != target) renameTo(target)
    target.deleteOnExit()
    return target
}
